# DATA CLEANING
# -----------------------------

df.columns = df.columns.str.strip()

df["Timestamp"] = pd.to_datetime(
    df["Timestamp"],
    errors="coerce"
)

df["Sales Count"] = pd.to_numeric(
    df["Sales Count"],
    errors="coerce"
).fillna(0)

df["Redemption Count"] = pd.to_numeric(
    df["Redemption Count"],
    errors="coerce"
).fillna(0)

df = df.dropna(subset=["Timestamp"])
df = df.drop_duplicates()

df["Sales Count"] = df["Sales Count"].clip(lower=0)
df["Redemption Count"] = df["Redemption Count"].clip(lower=0)

df = df.sort_values("Timestamp")

# -----------------------------
# FEATURES
# -----------------------------

df["Total Activity Load"] = (
    df["Sales Count"] +
    df["Redemption Count"]
)

df["Redemption Pressure Ratio"] = (
    df["Redemption Count"] /
    (df["Sales Count"] + 1)
)

df["Year"] = df["Timestamp"].dt.year
df["Month"] = df["Timestamp"].dt.month
df["Hour"] = df["Timestamp"].dt.hour

df["Day Type"] = np.where(
    df["Timestamp"].dt.dayofweek >= 5,
    "Weekend",
    "Weekday"
)

def season(month):
    if month in [3, 4, 5]:
        return "Spring"
    elif month in [6, 7, 8]:
        return "Summer"
    elif month in [9, 10, 11]:
        return "Fall"
    else:
        return "Winter"

df["Season"] = df["Month"].apply(season)

def time_band(hour):
    if 5 <= hour < 12:
        return "Morning"
    elif 12 <= hour < 17:
        return "Afternoon"
    elif 17 <= hour < 22:
        return "Evening"
    return "Night"

df["Time Band"] = df["Hour"].apply(time_band)

# -----------------------------
# OPERATIONAL LOAD INDEX
# -----------------------------

df["Rolling Load"] = (
    df["Total Activity Load"]
    .rolling(96, min_periods=1)
    .mean()
)

df["Load Percentile"] = (
    df["Total Activity Load"]
    .rank(pct=True)
)

deviation = (
    df["Total Activity Load"] -
    df["Rolling Load"]
) / (df["Rolling Load"] + 1)

deviation_score = (
    deviation.clip(-1, 1) + 1
) / 2

df["OLI"] = (
    0.70 * df["Load Percentile"] +
    0.30 * deviation_score
) * 100

df["OLI"] = df["OLI"].clip(0, 100)

congestion_threshold = df["OLI"].quantile(0.90)
idle_threshold = df["OLI"].quantile(0.10)

df["Congestion"] = (
    df["OLI"] >= congestion_threshold
)

df["Idle"] = (
    df["OLI"] <= idle_threshold
)

# Capacity proxy
reference_load = df["Redemption Count"].quantile(0.99)

df["Capacity Utilization Proxy"] = (
    df["Redemption Count"] /
    (reference_load + 1)
) * 100

df["Capacity Utilization Proxy"] = (
    df["Capacity Utilization Proxy"].clip(0, 100)
)

# -----------------------------
# SIDEBAR
# -----------------------------

st.sidebar.header("Dashboard Filters")

min_date = df["Timestamp"].min().date()
max_date = df["Timestamp"].max().date()

