# Time bands


def assign_time_band(hour):

    if 5 <= hour < 12:
        return "Morning"

    elif 12 <= hour < 17:
        return "Afternoon"

    elif 17 <= hour < 22:
        return "Evening"

    else:
        return "Night"


df["Time_Band"] = (
    df["Hour"]
    .apply(assign_time_band)
)



# Seasons


def assign_season(month):

    if month in [3, 4, 5]:
        return "Spring"

    elif month in [6, 7, 8]:
        return "Summer"

    elif month in [9, 10, 11]:
        return "Fall"

    else:
        return "Winter"


df["Season"] = (
    df["Month"]
    .apply(assign_season)
)

st.write(df.head())

# CELL 8 — CORE ANALYTICAL FEATURES


# Total Activity Load
df["Total_Activity_Load"] = (
    df["Sales Count"] +
    df["Redemption Count"]
)

# Redemption Pressure Ratio
df["Redemption_Pressure_Ratio"] = (
    df["Redemption Count"] /
    (df["Sales Count"] + 1)
)

# Zero activity
df["Zero_Activity_Flag"] = (
    df["Total_Activity_Load"] == 0
).astype(int)

st.write(
    df[
        [
            "Timestamp",
            "Sales Count",
            "Redemption Count",
            "Total_Activity_Load",
            "Redemption_Pressure_Ratio"
        ]
    ].head(15)
)

# CELL 9 — ROLLING BASELINE

# 15-minute data:
# 4 intervals = 1 hour
# 16 intervals = 4 hours
# 96 intervals = 24 hours

df["Rolling_1H_Load"] = (
    df["Total_Activity_Load"]
    .rolling(
        window=4,
        min_periods=1
    )
    .mean()
)

df["Rolling_4H_Load"] = (
    df["Total_Activity_Load"]
    .rolling(
        window=16,
        min_periods=1
    )
    .mean()
)

df["Rolling_24H_Load"] = (
    df["Total_Activity_Load"]
    .rolling(
        window=96,
        min_periods=1
    )
    .mean()
)

# Rolling standard deviation
df["Rolling_24H_Std"] = (
    df["Total_Activity_Load"]
    .rolling(
        window=96,
        min_periods=20
    )
    .std()
)

st.write(
    df[
        [
            "Timestamp",
            "Total_Activity_Load",
            "Rolling_1H_Load",
            "Rolling_4H_Load",
            "Rolling_24H_Load"
        ]
    ].head(20)
)

# CELL 10 — OPERATIONAL LOAD INDEX


# ------------------------------------------------------------
# Component 1: historical percentile rank

df["Load_Percentile"] = (
    df["Total_Activity_Load"]
    .rank(pct=True)
)


# ------------------------------------------------------------
# Component 2: deviation from 24-hour rolling baseline


df["Baseline_Deviation"] = (
    df["Total_Activity_Load"] -
    df["Rolling_24H_Load"]
)

df["Baseline_Deviation_Ratio"] = (
    df["Baseline_Deviation"] /
    (df["Rolling_24H_Load"] + 1)
)


# Convert deviation into 0–1 pressure score
deviation_score = (
    df["Baseline_Deviation_Ratio"]
    .clip(-1, 1)
    .add(1)
    .div(2)
)


# ------------------------------------------------------------
# Operational Load Index


df["OLI"] = (
    0.70 * df["Load_Percentile"] +
    0.30 * deviation_score
) * 100

df["OLI"] = (
    df["OLI"]
    .clip(0, 100)
)

st.write(
    df[
        [
            "Timestamp",
            "Total_Activity_Load",
            "Rolling_24H_Load",
            "Baseline_Deviation_Ratio",
            "OLI"
        ]
    ].head(20)
)

# CELL 11 — ADAPTIVE THRESHOLDS


# Historical percentile-based thresholds

CONGESTION_THRESHOLD = (
    df["OLI"].quantile(0.90)
)

HIGH_LOAD_THRESHOLD = (
    df["OLI"].quantile(0.75)
)

IDLE_THRESHOLD = (
    df["OLI"].quantile(0.10)
)

