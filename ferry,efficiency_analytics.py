# CELL 16 — CAPACITY UTILIZATION PROXY


print("""
IMPORTANT:
The dataset does not contain official vessel capacity.

Therefore this metric is an analytical proxy, not an observed
physical ferry capacity utilization percentage.
""")

# Use redemption activity as the passenger-throughput proxy.
# Normalize against the historical 99th percentile to avoid
# extreme outliers dominating the scale.

reference_load = (
    df["Redemption Count"]
    .quantile(0.99)
)

df["Capacity_Utilization_Proxy_%"] = (
    df["Redemption Count"] /
    (reference_load + 1)
) * 100

df["Capacity_Utilization_Proxy_%"] = (
    df["Capacity_Utilization_Proxy_%"]
    .clip(0, 100)
)

